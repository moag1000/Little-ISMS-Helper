<?php

declare(strict_types=1);

namespace App\Service\PolicyWizard;

use App\Entity\Document;
use App\Entity\PolicyAcknowledgement;
use App\Entity\Tenant;
use App\Entity\User;
use App\Exception\Tenant\TenantOrphanException;
use App\Repository\PolicyAcknowledgementRepository;
use App\Service\AuditLogger;
use DateTimeImmutable;
use Doctrine\ORM\EntityManagerInterface;

/**
 * Per-user acknowledgement collection service for published policies.
 *
 * Closes the auditor's predicted ISO 27001 A.6.3 NC ("policy must be
 * communicated and acknowledged"). Pairs with the
 * `PolicyAcknowledgementCoverageCheck` which queries this data via the
 * repository.
 *
 * Responsibilities:
 *   - request acknowledgements when a policy goes public (pre-flight,
 *     idempotent — a re-run does not create stale rows nor duplicate);
 *   - record acknowledgements with method + IP + version snapshot;
 *   - produce coverage statistics for the coverage check + dashboard widget.
 *
 * The service does NOT send emails / push notifications itself; that is
 * the responsibility of the caller (typically a CRON command). The
 * "request" call materialises the audit-trail "audience snapshot" so a
 * later auditor can verify that user X _was_ in scope at time T even
 * if they leave the company before acknowledging.
 *
 * Spec: ISO 27001 A.5.1, A.6.3 + ISO 27002 §6.3 awareness.
 */
final class PolicyAcknowledgementService
{
    public const METHOD_WEB_CLICK = 'web_click';
    public const METHOD_EMAIL_TOKEN = 'email_token';
    public const METHOD_TRAINING_PASS = 'training_pass';
    public const METHOD_SIGNED_PDF = 'signed_pdf';

    private const ALLOWED_METHODS = [
        self::METHOD_WEB_CLICK,
        self::METHOD_EMAIL_TOKEN,
        self::METHOD_TRAINING_PASS,
        self::METHOD_SIGNED_PDF,
    ];

    public function __construct(
        private readonly EntityManagerInterface $entityManager,
        private readonly PolicyAcknowledgementRepository $repository,
        private readonly PolicyAudienceResolver $audienceResolver,
        private readonly AuditLogger $auditLogger,
    ) {
    }

    /**
     * Whether a document asks its audience for an acknowledgement (ISO 27001 A.5.1/A.6.3):
     * the "Bestätigung erforderlich" switch on the document, or a policy generated by the
     * Policy-Wizard. Evidence uploads and other documents never ask anybody.
     */
    public static function needsAcknowledgement(Document $document): bool
    {
        return $document->getRequiresAcknowledgement() || $document->getGeneratedFromTemplate() !== null;
    }

    /**
     * The one version string an acknowledgement is stored under — the campaign rows, the
     * acknowledgement itself, coverage, inbox and My Day all read it from here, so a pending
     * row and the click that closes it always meet.
     *
     * Template version for Policy-Wizard documents, else the first 16 characters of the file's
     * SHA-256 (a new file = a new version to acknowledge), else the upload time.
     */
    public static function versionOf(Document $document): string
    {
        $vars = $document->getSubstitutionVariables();
        if (is_array($vars) && isset($vars['_template_version']) && (is_int($vars['_template_version']) || is_string($vars['_template_version']))) {
            return (string) $vars['_template_version'];
        }
        $hash = $document->getSha256Hash();
        if (is_string($hash) && $hash !== '') {
            return substr($hash, 0, 16);
        }
        // Last resort — uploadedAt timestamp; columns are length 32 so
        // we keep the value compact.
        $uploadedAt = $document->getUploadedAt();
        if ($uploadedAt !== null) {
            return $uploadedAt->format('YmdHis');
        }

        return '1';
    }

    /**
     * Pending rows (not yet persisted) for every member of the current audience who has no
     * row for the current version yet. Callers persist them — the campaign listener after the
     * flush, {@see requestAcknowledgements()} directly.
     *
     * @param list<User> $audience explicit audience; empty = {@see PolicyAudienceResolver}
     *
     * @return list<PolicyAcknowledgement>
     */
    public function missingRequests(Document $document, array $audience = []): array
    {
        $tenant = $document->getTenant();
        if (!$tenant instanceof Tenant || !self::needsAcknowledgement($document)) {
            return [];
        }
        if ($audience === []) {
            $audience = $this->audienceResolver->resolveAudience($document);
        }

        $version = self::versionOf($document);
        $rows = [];
        $seen = [];
        foreach ($audience as $user) {
            if (!$user->isActive() || isset($seen[spl_object_id($user)])) {
                continue;
            }
            $seen[spl_object_id($user)] = true;
            if ($this->repository->findOneFor($tenant, $document, $user, $version) instanceof PolicyAcknowledgement) {
                continue;
            }
            $pending = new PolicyAcknowledgement();
            $pending->setTenant($tenant);
            $pending->setDocument($document);
            $pending->setUser($user);
            $pending->setDocumentVersion($version);
            // The constructor pre-fills acknowledgedAt + method; a pending row has neither.
            $pending->setStatus(PolicyAcknowledgement::STATUS_PENDING);
            $pending->setAcknowledgedAt(null);
            $pending->setAcknowledgementMethod(null);
            $rows[] = $pending;
        }

        return $rows;
    }

    /**
     * Raise the open acknowledgement requests of a published document: a pending row for
     * every audience member without one for the current version (people who joined later
     * included), and away with pending rows nobody can close any more — an older version, a
     * person who left the audience or was deactivated, a document that no longer asks for
     * acknowledgement. Acknowledged rows are evidence and stay. Persists, the caller flushes.
     *
     * Returns the number of users that still owe an acknowledgement after this call.
     *
     * @param list<User> $audience explicit audience override; falls back
     *                             to {@see PolicyAudienceResolver} when empty.
     */
    public function requestAcknowledgements(Document $document, array $audience = []): int
    {
        $tenant = $document->getTenant();
        if (!$tenant instanceof Tenant) {
            throw new TenantOrphanException(null, 'Document must be tenant-scoped before acknowledgement requests can be raised.');
        }

        if ($audience === []) {
            $audience = $this->audienceResolver->resolveAudience($document);
        }
        $needed = self::needsAcknowledgement($document);
        $version = self::versionOf($document);
        $audienceIds = [];
        foreach ($audience as $user) {
            if ($user->isActive() && $user->getId() !== null) {
                $audienceIds[$user->getId()] = true;
            }
        }

        $this->withdraw($document, $needed ? $audienceIds : [], $version);

        if (!$needed) {
            return 0;
        }
        foreach ($this->missingRequests($document, $audience) as $row) {
            $this->entityManager->persist($row);
        }

        $pending = 0;
        foreach ($audience as $user) {
            if (!$user instanceof User || !$user->isActive()) {
                continue;
            }
            $existing = $this->repository->findOneFor($tenant, $document, $user, $version);
            if ($existing instanceof PolicyAcknowledgement
                && $existing->getStatus() === PolicyAcknowledgement::STATUS_ACKNOWLEDGED) {
                continue;
            }
            $pending++;
        }

        return $pending;
    }

    /**
     * Withdraw every open request of a document that left publication (archived, back to
     * draft): nobody can acknowledge it there, so nothing may remind or block on it.
     */
    public function withdrawOpenRequests(Document $document): int
    {
        return $this->withdraw($document, [], self::versionOf($document));
    }

    /**
     * Remove pending rows of the document that are not owed any more: another version, or a
     * user outside $audienceIds (empty = everybody's). Acknowledged rows stay as evidence.
     *
     * @param array<int, true> $audienceIds
     */
    private function withdraw(Document $document, array $audienceIds, string $version): int
    {
        $removed = [];
        foreach ($this->repository->findPendingByDocument($document) as $row) {
            $user = $row->getUser();
            if ($row->getDocumentVersion() === $version && $user instanceof User && isset($audienceIds[(int) $user->getId()])) {
                continue;
            }
            $removed[(int) $row->getId()] = [
                'user_id' => $user?->getId(),
                'document_version' => $row->getDocumentVersion(),
            ];
            $this->entityManager->remove($row);
        }
        if ($removed !== []) {
            $this->auditLogger->logBulk(
                eventType: 'policy-acknowledgement.pending-withdrawn',
                entityType: 'PolicyAcknowledgement',
                batchData: ['document_id' => $document->getId(), 'current_version' => $version],
                perEntityData: $removed,
                description: sprintf('%d open acknowledgement request(s) of document #%d withdrawn (old version, left audience or no longer required)', count($removed), (int) $document->getId()),
            );
        }

        return count($removed);
    }

    /**
     * Record a single acknowledgement. Throws when the unique constraint
     * (tenant, document, user, version) is already satisfied.
     */
    public function acknowledge(
        Document $document,
        User $user,
        string $method,
        ?string $ipAddress = null,
    ): PolicyAcknowledgement {
        if (!in_array($method, self::ALLOWED_METHODS, true)) {
            throw new \App\Exception\InvalidArgument\InvalidArgumentException(sprintf(
                'Acknowledgement method "%s" is not supported. Allowed: %s.',
                $method,
                implode(', ', self::ALLOWED_METHODS),
            ));
        }
        $tenant = $document->getTenant();
        if (!$tenant instanceof Tenant) {
            throw new TenantOrphanException(null, 'Document must be tenant-scoped to be acknowledged.');
        }

        $version = self::versionOf($document);

        $existing = $this->repository->findOneFor($tenant, $document, $user, $version);

        // An existing PENDING row (from the auto-campaign)
        // is upgraded in-place to ACKNOWLEDGED. Only an existing
        // ACKNOWLEDGED row blocks the call.
        if ($existing instanceof PolicyAcknowledgement
            && $existing->getStatus() === PolicyAcknowledgement::STATUS_ACKNOWLEDGED) {
            throw new \App\Exception\BusinessRule\BusinessRuleException(sprintf(
                'User %d has already acknowledged Document %d at version %s.',
                $user->getId() ?? -1,
                $document->getId() ?? -1,
                $version,
            ));
        }

        $ack = $existing instanceof PolicyAcknowledgement ? $existing : new PolicyAcknowledgement();
        $ack->setTenant($tenant);
        $ack->setDocument($document);
        $ack->setUser($user);
        $ack->setStatus(PolicyAcknowledgement::STATUS_ACKNOWLEDGED);
        $ack->setAcknowledgedAt(new DateTimeImmutable());
        $ack->setAcknowledgementMethod($method);
        $ack->setDocumentVersion($version);
        $ack->setIpAddress($ipAddress);

        if (!$ack->getId()) {
            $this->entityManager->persist($ack);
        }
        $this->entityManager->flush();

        $this->auditLogger->logCustom(
            action: 'policy-acknowledgement',
            entityType: 'PolicyAcknowledgement',
            entityId: $ack->getId(),
            newValues: [
                'document_id' => $document->getId(),
                'user_id' => $user->getId(),
                'method' => $method,
                'document_version' => $version,
            ],
            description: sprintf(
                'User %s acknowledged document #%d (v%s) via %s',
                (string) $user->getEmail(),
                (int) $document->getId(),
                $version,
                $method,
            ),
        );

        return $ack;
    }

    /**
     * Coverage tally for a single Document. Returns:
     *   acknowledged       — number of distinct users that acknowledged
     *                        the current version of the document;
     *   pending            — audience size minus acknowledged;
     *   percent            — round((acknowledged / audience) * 100, 1);
     *                        100.0 when audience is zero (audit-defang
     *                        for empty/sandbox tenants);
     *   audience_user_ids  — list<int> of resolved audience user IDs.
     *
     * @return array{acknowledged: int, pending: int, percent: float, audience_user_ids: list<int>}
     */
    public function coverageFor(Document $document): array
    {
        $audience = $this->audienceResolver->resolveAudience($document);
        $audienceIds = [];
        foreach ($audience as $user) {
            $id = $user->getId();
            if ($id !== null) {
                $audienceIds[] = $id;
            }
        }
        $audienceSize = count($audienceIds);

        if ($audienceSize === 0) {
            return [
                'acknowledged' => 0,
                'pending' => 0,
                'percent' => 100.0,
                'audience_user_ids' => [],
            ];
        }

        $version = self::versionOf($document);
        $tenant = $document->getTenant();

        $acknowledged = 0;
        if ($tenant instanceof Tenant) {
            foreach ($audience as $user) {
                $existing = $this->repository->findOneFor($tenant, $document, $user, $version);
                // Only ACKNOWLEDGED rows count toward coverage —
                // pending campaign rows are tracked but unsigned.
                if ($existing instanceof PolicyAcknowledgement
                    && $existing->getStatus() === PolicyAcknowledgement::STATUS_ACKNOWLEDGED) {
                    $acknowledged++;
                }
            }
        }

        $pending = $audienceSize - $acknowledged;
        $percent = round(($acknowledged / $audienceSize) * 100.0, 1);

        return [
            'acknowledged' => $acknowledged,
            'pending' => $pending,
            'percent' => $percent,
            'audience_user_ids' => $audienceIds,
        ];
    }

    /**
     * Pending documents for a single user — drives the inbox UX.
     *
     * @return list<Document>
     */
    public function pendingDocumentsForUser(User $user): array
    {
        $tenant = $user->getTenant();
        if (!$tenant instanceof Tenant) {
            return [];
        }

        // Walk all published documents in the tenant; check audience
        // membership; skip already-acked. The lookup is idempotent and
        // safe to run on every page-load (small dataset — published
        // policies are dozens, not thousands).
        $documents = $this->entityManager->getRepository(Document::class)
            ->createQueryBuilder('d')
            ->where('d.tenant = :tenant')
            ->andWhere('d.status IN (:statuses)')
            ->andWhere('d.isArchived = false')
            ->setParameter('tenant', $tenant)
            ->setParameter('statuses', ['published', 'approved'])
            ->getQuery()
            ->getResult();

        $pending = [];
        foreach ($documents as $document) {
            if (!$document instanceof Document || !self::needsAcknowledgement($document)) {
                continue;
            }
            $audience = $this->audienceResolver->resolveAudience($document);
            $isInAudience = false;
            foreach ($audience as $candidate) {
                if ($candidate->getId() === $user->getId()) {
                    $isInAudience = true;
                    break;
                }
            }
            if (!$isInAudience) {
                continue;
            }
            $version = self::versionOf($document);
            $existing = $this->repository->findOneFor($tenant, $document, $user, $version);
            // PENDING rows still count as "pending"
            // (auto-campaign created an audit-trail row but the user
            // hasn't clicked through). Only ACKNOWLEDGED rows close
            // the loop.
            if ($existing instanceof PolicyAcknowledgement
                && $existing->getStatus() === PolicyAcknowledgement::STATUS_ACKNOWLEDGED) {
                continue;
            }
            $pending[] = $document;
        }
        return $pending;
    }
}
