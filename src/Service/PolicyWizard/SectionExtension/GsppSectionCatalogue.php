<?php

declare(strict_types=1);

namespace App\Service\PolicyWizard\SectionExtension;

use App\Service\Bsi\GsppReuseMap;

/**
 * Policy-Wizard — BSI Grundschutz++ (BSI-Standard 300-1) section-extension catalogue.
 *
 * Extends each ISO 27001 topic policy with the Grundschutz++ requirements the BSI maps
 * to the topic's Annex A controls (official mapping ISO/IEC 27001:2022 → GS++); the
 * top-level policy also carries the requirements behind ISO clauses 4.3, 5.1–5.3 and 6.2.
 *
 * Data: {@see GsppReuseMap::policyTopics()} and the prose in `translations/policy_gspp.{de,en}.yaml` — both
 * generated by `scripts/library/build_gspp_policy_sections.py`, so the requirement IDs
 * listed in the policy text and the controlRefs used for cross-coverage are the same.
 */
final class GsppSectionCatalogue implements StandardSectionCatalogueInterface
{
    public const string STANDARD = 'gspp';

    public function __construct(
        private readonly GsppReuseMap $reuseMap,
    ) {
    }

    public function getStandard(): string
    {
        return self::STANDARD;
    }

    /** @return list<SectionExtension> */
    public function sectionsForTopic(string $isoTopic): array
    {
        $refs = $this->reuseMap->policyTopics()[$isoTopic] ?? [];
        if ($refs === []) {
            return [];
        }

        return [
            new SectionExtension(
                sectionKey:         'gspp_extension',
                standard:           self::STANDARD,
                controlRefs:        $refs,
                approvalRole:       'ciso',
                bodyTranslationKey: sprintf('policy.iso27001.%s.v1.gspp_extension.body', $isoTopic),
                renderMode:         'body_extension',
            ),
        ];
    }
}
