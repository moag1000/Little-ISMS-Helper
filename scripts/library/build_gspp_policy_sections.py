#!/usr/bin/env python3
"""Build the Grundschutz++ reuse map and the GS++ policy section texts.

Usage: python3 scripts/library/build_gspp_policy_sections.py

Inputs (all in the repo, nothing is fetched):
  - fixtures/library/catalogues/bsi-grundschutz-plusplus/catalogue.json
  - fixtures/library/mappings/iso27001-2022_to_bsi-gspp_official_v1.yaml  (amtliches BSI-Mapping)
  - fixtures/library/mappings/iso27001-2022-clauses_to_bsi-gspp_v1.yaml
  - src/Command/SeedIsoPolicyTemplatesCommand.php  (ISO topic -> Annex A controls)

Outputs:
  - fixtures/library/catalogues/bsi-grundschutz-plusplus/reuse_map.json
      policy_topics: ISO policy topic -> GS++ requirement IDs (GsppSectionCatalogue)
      practice_iso_controls: GS++ practice -> ISO Annex A control IDs (compliance wizard)
  - translations/policy_gspp.{de,en}.yaml
      policy.iso27001.<topic>.v1.gspp_extension.body — appended to the ISO topic policy
      when the policy wizard run adopts the 'gspp' standard.

A topic gets the GS++ requirements the BSI maps to its Annex A controls; the top-level
policy also gets the requirements behind the ISO clauses it answers (scope, leadership,
policy, roles, objectives). Deterministic — rerun after the catalogue or a mapping changes.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
GSPP_DIR = ROOT / 'fixtures/library/catalogues/bsi-grundschutz-plusplus'
MAPPINGS = ROOT / 'fixtures/library/mappings'
ISO_SEED = ROOT / 'src/Command/SeedIsoPolicyTemplatesCommand.php'
TRANSLATIONS = ROOT / 'translations'

TOP_LEVEL_CLAUSES = ['ISO27001-4.3', 'ISO27001-5.1', 'ISO27001-5.2', 'ISO27001-5.3', 'ISO27001-6.2']
TIER_ORDER = {'basis': 0, 'standard': 1, 'hoch': 2}
TIER_LABEL = {
    'de': {'basis': 'Basis', 'standard': 'Standard', 'hoch': 'Hoch'},
    'en': {'basis': 'Basic', 'standard': 'Standard', 'hoch': 'High'},
}
HEADER = '# GENERATED by scripts/library/build_gspp_policy_sections.py — do not edit by hand.\n'

TEXT = {
    'de': {
        'heading': '## Ergänzung Grundschutz++ (BSI-Standard 300-1)',
        'intro': (
            'Diese Richtlinie setzt zusätzlich die folgenden Anforderungen des Anwenderkatalogs '
            'Grundschutz++ um. Basis-Anforderungen (MUSS) gelten immer. Standard-Anforderungen '
            'gelten auf dem Sicherheitsniveau „normal (Stand der Technik)“, Anforderungen der Stufe '
            'Hoch bei erhöhtem Schutzbedarf. Welche Anforderungen für ein Zielobjekt gelten, legt das '
            'Anforderungspaket der Strukturmodellierung (STM.2) fest; Abweichungen werden im '
            'Ausnahmemanagement (UMS.5) begründet und genehmigt.'
        ),
        'method': (
            'Das ISMS folgt der Methodik nach BSI-Standard 300-1: Strukturmodellierung des '
            'Informationsverbunds (STM), Umsetzungsplanung und -verfolgung (UMS), Monitoring und '
            'Evaluation (PERF) sowie kontinuierliche Verbesserung (VRB).'
        ),
        'cols': '| Anforderung | Titel | Stufe |',
        'source': (
            '*Quelle: BSI, Anwenderkatalog Grundschutz++ (CC BY-SA 4.0). Zuordnung über das amtliche '
            'BSI-Mapping ISO/IEC 27001:2022 → Grundschutz++.*'
        ),
    },
    'en': {
        'heading': '## Grundschutz++ supplement (BSI Standard 300-1)',
        'intro': (
            'This policy additionally implements the following requirements of the BSI Grundschutz++ '
            'user catalogue. Basic requirements (MUSS) always apply. Standard requirements apply at the '
            'security level "normal (state of the art)", requirements of the High tier apply to raised '
            'protection needs. The requirement package of the structure model (STM.2) defines which '
            'requirements apply to a target object; deviations are justified and approved in exception '
            'management (UMS.5). Requirement titles are quoted from the German original.'
        ),
        'method': (
            'The ISMS follows the methodology of BSI Standard 300-1: structure model of the information '
            'domain (STM), implementation planning and tracking (UMS), monitoring and evaluation (PERF) '
            'and continual improvement (VRB).'
        ),
        'cols': '| Requirement | Title | Tier |',
        'source': (
            '*Source: BSI, Grundschutz++ user catalogue (CC BY-SA 4.0). Assignment via the official BSI '
            'mapping ISO/IEC 27001:2022 → Grundschutz++.*'
        ),
    },
}


def natural_key(identifier: str) -> list:
    return [int(p) if p.isdigit() else p for p in re.split(r'(\d+)', identifier)]


def iso_topics() -> dict[str, list[str]]:
    """Topic -> linked Annex A controls, read from SeedIsoPolicyTemplatesCommand::TEMPLATES."""
    php = ISO_SEED.read_text(encoding='utf-8')
    pairs = re.findall(
        r"'topic' => '([a-z_]+)',.*?'linked_annex_a_controls' => \[([^\]]*)\]",
        php,
        flags=re.S,
    )
    topics = {topic: re.findall(r"'(A\.\d+\.\d+)'", controls) for topic, controls in pairs}
    if len(topics) != 25:
        raise SystemExit(f'expected 25 ISO topics in {ISO_SEED.name}, found {len(topics)}')
    return topics


def mapping_targets(name: str) -> dict[str, set[str]]:
    data = yaml.safe_load((MAPPINGS / name).read_text(encoding='utf-8'))
    out: dict[str, set[str]] = defaultdict(set)
    for entry in data['mappings']:
        for target in entry.get('targets') or [entry['target']]:
            out[str(entry['source'])].add(str(target))
    return out


def body(lang: str, ids: list[str], catalogue: dict[str, dict], with_method: bool) -> str:
    t = TEXT[lang]
    lines = [t['heading'], '', t['intro'], '']
    if with_method:
        lines += [t['method'], '']
    lines += [t['cols'], '|---|---|---|']
    for rid in ids:
        row = catalogue[rid]
        title = row['title'].replace('|', '/')
        lines.append(f"| {rid} | {title} | {TIER_LABEL[lang][row['tier']]} ({row['modal_verb']}) |")
    lines += ['', t['source']]
    return '\n'.join(lines)


class _Dumper(yaml.SafeDumper):
    pass


_Dumper.add_representer(
    str,
    lambda d, s: d.represent_scalar('tag:yaml.org,2002:str', s, style='|' if '\n' in s else None),
)


def main() -> None:
    catalogue = {
        row['id']: row
        for row in json.loads((GSPP_DIR / 'catalogue.json').read_text(encoding='utf-8'))['requirements']
    }
    annex = mapping_targets('iso27001-2022_to_bsi-gspp_official_v1.yaml')
    clauses = mapping_targets('iso27001-2022-clauses_to_bsi-gspp_v1.yaml')

    def ordered(ids: set[str]) -> list[str]:
        return sorted(ids, key=lambda i: (TIER_ORDER[catalogue[i]['tier']], natural_key(i)))

    policy_topics: dict[str, list[str]] = {}
    for topic, controls in iso_topics().items():
        ids: set[str] = set()
        for control in controls:
            ids |= annex.get(control, set())
        if topic == 'top_level':
            for clause in TOP_LEVEL_CLAUSES:
                ids |= clauses.get(clause, set())
        if ids:
            policy_topics[topic] = ordered(ids)

    practice_iso: dict[str, set[str]] = defaultdict(set)
    for control, targets in annex.items():
        for target in targets:
            practice_iso[catalogue[target]['practice']].add(control.removeprefix('A.'))

    reuse_map = {
        '_generated_by': 'scripts/library/build_gspp_policy_sections.py',
        'policy_topics': dict(sorted(policy_topics.items())),
        'practice_iso_controls': {
            practice: sorted(controls, key=natural_key) for practice, controls in sorted(practice_iso.items())
        },
    }
    (GSPP_DIR / 'reuse_map.json').write_text(
        json.dumps(reuse_map, ensure_ascii=False, indent=2) + '\n', encoding='utf-8'
    )

    for lang in ('de', 'en'):
        topics = {
            topic: {'v1': {'gspp_extension': {'body': body(lang, ids, catalogue, topic == 'top_level')}}}
            for topic, ids in sorted(policy_topics.items())
        }
        doc = {'policy': {'iso27001': topics}}
        text = yaml.dump(doc, Dumper=_Dumper, allow_unicode=True, sort_keys=False, width=1000, indent=4)
        (TRANSLATIONS / f'policy_gspp.{lang}.yaml').write_text(HEADER + text, encoding='utf-8')

    print(f'{len(policy_topics)} policy topics, {len(practice_iso)} practices with ISO controls')
    for topic, ids in sorted(policy_topics.items()):
        print(f'  {topic}: {len(ids)}')


if __name__ == '__main__':
    main()
